import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const out = join(tmpdir(), "chainbot-aave-reader-out");
execFileSync("forge", ["build", "--skip", "test", "--root", join(root, "contracts/aave-v4"), "--out", out,
  "--cache-path", join(tmpdir(), "chainbot-aave-reader-cache")], { stdio: "inherit" });
const artifact = JSON.parse(readFileSync(join(out, "AaveV4ConfigReader.sol/AaveV4ConfigReader.json"), "utf8"));
const content = "//native\n\n// Generated by scripts/build-aave-reader.mjs; Solidity/compiler settings are in contracts/aave-v4.\n"
  + `export const READER_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`
  + `export const READER_BYTECODE = "${artifact.bytecode.object}" as const;\n`
  + `export const READER_RUNTIME_BYTECODE = "${artifact.deployedBytecode.object}" as const;\n`;
const path = join(root, "f/aave/lib/market-params-reader-artifact.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== content) throw new Error("Aave reader artifact is stale; run node scripts/build-aave-reader.mjs");
} else writeFileSync(path, content);
console.log(`Reader creation bytecode: ${(artifact.bytecode.object.length - 2) / 2} bytes`);
